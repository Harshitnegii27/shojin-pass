#!/usr/bin/env node
// Writes docs/rulebook-review.md: a checklist of every rulebook entry for the team's human review
// (spec 8.5: two reviewers per entry). Reads the rulebook; never changes it.
//   node scripts/genRulebookReview.js            writes docs/rulebook-review.md
//   node scripts/genRulebookReview.js --stdout   prints it instead
// Regenerating overwrites ticks made in the file. The real record is `reviewedBy` in ingredients.json.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readRulebookFiles, reviewerCount } from '../lib/rulebook/loader.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs', 'rulebook-review.md');

// Colour of a list of tags for one diet or option: red if any tag is forbidden, amber if any is asked.
// The same rule as the engine's tag table (spec 8.1–8.3); the engine stays the source of truth.
export function colourFor(tags, rule) {
  if (tags.some((t) => (rule.forbid || []).includes(t))) return 'red';
  if (tags.some((t) => (rule.ask || []).includes(t))) return 'amber';
  return 'green';
}

const list = (xs) => (xs.length ? xs.join(', ') : '—');

function verdictLines(tags, diets, options) {
  const ids = Object.keys(diets);
  const by = (c) => ids.filter((d) => colourFor(tags, diets[d]) === c);
  const red = by('red');
  const amber = by('amber');
  const lines = red.length || amber.length
    ? [`Red (avoid) for: ${red.length === ids.length ? 'all diets' : list(red)}`, `Amber (ask) for: ${list(amber)}`]
    : ['Not flagged for any diet (green)'];
  const opts = Object.entries(options)
    .filter(([, o]) => !o.routesOnly && colourFor(tags, o) !== 'green')
    .map(([id, o]) => `${id} → ${colourFor(tags, o)}`);
  if (opts.length) lines.push(`With options: ${opts.join(', ')}`);
  return lines;
}

export function buildReviewDoc(data) {
  const { meta, tags, diets, options, ingredients } = data;
  const dietIds = Object.keys(diets);
  const reviewed = ingredients.filter((e) => reviewerCount(e) >= 2).length;
  const out = [];
  const w = (s = '') => out.push(s);

  w('# Rulebook review checklist');
  w();
  w(`Rulebook version **${meta.version}** (updated ${meta.updated}), status: ${meta.status}.`);
  w(`**${ingredients.length} entries, ${reviewed} reviewed by two people, ${ingredients.length - reviewed} still to review.**`);
  w();
  w('Generated by `node scripts/genRulebookReview.js` from the files in `rulebook/`. Do not edit the');
  w('rulebook through this file: running the script again overwrites any ticks made here.');
  w();
  w('## How to review');
  w();
  w('Every entry needs **two different reviewers** before release (spec 8.5). Until then the server');
  w('treats it as unreviewed, and in production every label comes out amber. For each entry check:');
  w();
  w('1. **Meaning:** is the English meaning right for how the word is used on Japanese labels?');
  w('2. **Spellings:** is every spelling really this ingredient? Anything missing (kanji, kana, katakana)?');
  w('3. **Tags and diets:** are the "Red" and "Amber" diets right? Red means definitely avoided; amber means');
  w('   "ask staff" (source not stated, or some people avoid it). When unsure, amber is the safe choice;');
  w('   green is never a guess.');
  w('4. Tick the box and write your name. When an entry has two names, a teammate adds both names to its');
  w('   `reviewedBy` list in `rulebook/ingredients.json` in a pull request, runs');
  w('   `node scripts/validateRulebook.js`, bumps `meta.json` and adds a line to `rulebook/CHANGELOG.md`.');
  w('   Corrections (wrong tag, missing spelling) go in the same kind of pull request.');
  w();
  w('Composite entries (marked *composite*) are words for mixtures, such as だし or キムチ, whose real');
  w('contents are not stated on the label.');
  w();
  w('## Diets');
  w();
  w('| Diet id | Name | Red (forbidden) tags | Amber (ask) tags |');
  w('|---|---|---|---|');
  for (const id of dietIds) w(`| \`${id}\` | ${diets[id].label.en} | ${list(diets[id].forbid)} | ${list(diets[id].ask)} |`);
  w();
  w('Options a user can add:');
  w();
  for (const [id, o] of Object.entries(options)) {
    const what = o.routesOnly ? 'routes only, not used for labels'
      : o.askSharedLine ? 'shared-line notices become amber'
      : [o.forbid?.length ? `red: ${o.forbid.join(', ')}` : '', o.ask?.length ? `amber: ${o.ask.join(', ')}` : ''].filter(Boolean).join('; ');
    w(`- \`${id}\`: ${o.label.en} (${what})`);
  }
  w();
  w('## Tags');
  w();
  w('| Tag | Meaning | Red for | Amber for |');
  w('|---|---|---|---|');
  for (const [id, t] of Object.entries(tags)) {
    const red = dietIds.filter((d) => colourFor([id], diets[d]) === 'red');
    const amber = dietIds.filter((d) => colourFor([id], diets[d]) === 'amber');
    w(`| \`${id}\` | ${t.label.en}${t.description ? ` — ${t.description}` : ''} | ${list(red)} | ${list(amber)} |`);
  }
  w();
  w('## Entries');
  w();
  w('Grouped by first tag, in rulebook order.');

  const groups = new Map();
  for (const e of ingredients) {
    const g = e.tags[0] || 'untagged';
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(e);
  }
  let n = 0;
  for (const [g, entries] of groups) {
    w();
    w(`### ${tags[g]?.label.en || g} (\`${g}\`, ${entries.length})`);
    w();
    for (const e of entries) {
      n++;
      const count = reviewerCount(e);
      const status = count >= 2 ? `reviewed (${e.reviewedBy.join(', ')})` : `draft, ${count}/2 reviewers${count ? ` (${e.reviewedBy.join(', ')})` : ''}`;
      w(`- [ ] **${n}. \`${e.id}\`: ${e.canonical}** — ${e.meaning.en}${e.composite ? ' *(composite)*' : ''}`);
      w(`  - Spellings (${e.aliases.length}): ${e.aliases.join('、')}`);
      w(`  - Tags: ${e.tags.map((t) => `\`${t}\``).join(', ')}`);
      for (const l of verdictLines(e.tags, diets, options)) w(`  - ${l}`);
      w(`  - Status: ${status}, added in ${e.addedIn}`);
      w('  - Reviewer 1: ________  Reviewer 2: ________  Notes: ________');
    }
  }
  w();
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const doc = buildReviewDoc(readRulebookFiles());
  if (process.argv.includes('--stdout')) process.stdout.write(doc);
  else {
    fs.writeFileSync(OUT, doc);
    console.log(`Wrote ${path.relative(ROOT, OUT)}`);
  }
}
